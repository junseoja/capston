-- ============================================================
-- 2026-05-20 마이그레이션 — users.bio 컬럼 추가 (프로필 수정 백엔드)
-- ============================================================
-- 배경:
--   5/19 인스타 스타일 프로필 편집 UI 가 머지되며 닉네임과 함께 자기소개(bio) 입력 필드가
--   추가되었으나, users 테이블에는 bio 컬럼이 없어 새로고침 시 입력값이 모두 사라지고
--   클라이언트 상태로만 휘발되었음(P0 #2). 백엔드 PATCH /user/profile 엔드포인트를 추가하면서
--   영속 저장이 가능하도록 컬럼을 추가한다.
--
-- 적용 전 주의:
--   1. AWS RDS 스냅샷 후 실행 권장.
--   2. 기존 users 행은 bio = NULL 로 자동 채워짐 → 기존 동작 영향 없음.
--   3. 프로필 사진(profile_img) 은 본 마이그레이션 범위 밖. 이미 컬럼 존재.
--
-- 영향:
--   - users.bio NULL = 미작성, NOT NULL = 사용자가 저장한 자기소개
--   - FastAPI PATCH /user/profile/{user_id} : nickname / bio 동시 갱신
--   - Express GET /me 응답에 bio 포함
--   - React MyPage.jsx 가 user.bio 를 초기값으로 사용
-- ============================================================

ALTER TABLE users
    ADD COLUMN bio VARCHAR(300) NULL
    COMMENT '자기소개 (2026-05-20 추가, 인스타 스타일 프로필 편집)'
    AFTER profile_img;


-- ============================================================
-- 적용 후 검증
-- ============================================================
--   DESCRIBE users;                              -- bio 컬럼 보이는지
--   SELECT user_id, nickname, bio FROM users LIMIT 5;
--
--   그 다음 앱에서:
--   - GET /me                       → user.bio 필드 존재 (값은 null)
--   - PATCH /me/profile {nickname, bio} → 응답 success: true
--   - 다시 GET /me                   → 저장된 bio 가 노출
-- ============================================================


